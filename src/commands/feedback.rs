//! `feedback`: submit user feedback or feature requests via GitHub issue.

use clap::Args;
use serde::Serialize;
use serde_json::Value;

use super::support::{REPORT_REPO, open_in_browser, urlencoding};
use crate::command_spec::{CliCommand, CommandSpec, DryRunPolicy, InputKind, Lifecycle, Risk, arg};
use crate::invocation::Invocation;
use crate::output::TableData;

#[derive(Args, Debug, Clone)]
pub struct FeedbackArgs {
    /// Message or feature description.
    #[arg(value_name = "MESSAGE")]
    pub message: Option<String>,

    /// Category or tag for the feedback (e.g. feature, docs, ux).
    #[arg(long, value_name = "CATEGORY", default_value = "general")]
    pub category: String,

    /// Title for the GitHub issue.
    #[arg(long, value_name = "TITLE")]
    pub title: Option<String>,

    /// Open issue in web browser if running in an interactive terminal.
    #[arg(long)]
    pub open: bool,
}

#[derive(Debug, Clone, Serialize)]
pub struct FeedbackOutput {
    pub url: String,
    pub title: String,
    pub body: String,
    pub opened_in_browser: bool,
}

impl TableData for FeedbackOutput {
    fn headers(&self) -> Vec<&str> {
        vec!["Title", "URL"]
    }

    fn rows(&self) -> Vec<Vec<String>> {
        vec![vec![self.title.clone(), self.url.clone()]]
    }

    fn to_json_value(&self) -> Value {
        serde_json::to_value(self).unwrap_or(Value::Null)
    }
}

pub struct Feedback;

impl CliCommand for Feedback {
    type Args = FeedbackArgs;

    const SPEC: CommandSpec = CommandSpec::read(
        &["feedback"],
        "system",
        "Generate or submit feedback and feature requests to GitHub",
        "Generates a pre-filled GitHub issue URL for user suggestions and feature requests with CLI version and platform context. Agents can read the issue URL and markdown body directly from JSON.",
    )
    .lifecycle(Lifecycle::InteractiveLocal)
    .risk(Risk::None)
    .dry_run(DryRunPolicy::NotSupported)
    .local()
    .args(&[
        arg("message").kind(InputKind::Identifier),
        arg("category").kind(InputKind::Identifier),
        arg("title").kind(InputKind::Identifier),
    ]);

    async fn run(inv: &Invocation, args: &FeedbackArgs) -> Result<(), anyhow::Error> {
        let version = env!("CARGO_PKG_VERSION");
        let os = std::env::consts::OS;
        let arch = std::env::consts::ARCH;

        let msg = args.message.as_deref().unwrap_or("Feedback / suggestion");
        let default_title = format!("Feedback [{}]: {}", args.category, msg);
        let title = args.title.clone().unwrap_or(default_title);

        let body = format!(
            "### User Feedback\n\n\
            - **CLI Version**: `{version}`\n\
            - **Platform**: `{os}/{arch}`\n\
            - **Category**: `{}`\n\n\
            ### Description\n\
            {}\n\n\
            *Generated by hyperliquid feedback*",
            args.category, msg
        );

        let encoded_title = urlencoding(&title);
        let encoded_body = urlencoding(&body);
        let label = format!("feedback,{}", args.category);
        let url = format!(
            "https://github.com/{REPORT_REPO}/issues/new?title={encoded_title}&body={encoded_body}&labels={label}"
        );

        let opened = if args.open {
            open_in_browser(&url)
        } else {
            false
        };

        let output = FeedbackOutput {
            url,
            title,
            body,
            opened_in_browser: opened,
        };

        inv.print(&output);
        Ok(())
    }
}
